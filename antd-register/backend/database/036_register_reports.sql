-- Add the non-macro register report to the retained export preparation protocol.
-- Every prior kind/module alternative from029 is retained without a data rewrite.
alter table replacement_register.preparation_jobs drop constraint preparation_kind_module;
alter table replacement_register.preparation_jobs add constraint preparation_kind_module check (coalesce((
  (coalesce(descriptor->>'kind','EXPORT')='EXPORT' and descriptor->>'moduleId' in ('M01','M03','M05','M06','M07','M09','REGISTER_REPORT'))
  or (descriptor->>'kind'='IMPORT' and descriptor->>'moduleId' in ('M02','M04','M08'))
  or (descriptor->>'kind' in ('INSPECT','REGISTER_BOM') and descriptor->>'moduleId'='M01')
  or (descriptor->>'kind' in ('ATTACHMENT','RESCAN') and descriptor->'moduleId'='null'::jsonb)
),false));

alter table replacement_register.artifacts add constraint register_report_artifact_shape check (
  module_id is distinct from 'REGISTER_REPORT' or coalesce(
    kind in ('WORKFLOW_INPUT','WORKFLOW_OUTPUT') and owner_only
    and jsonb_typeof(scope_json->'reportOwnerRole')='string'
    and scope_json->>'reportOwnerRole' in ('ADMINISTRATOR','SUPPLIER','CLIENT'),false)
);
create function replacement_register.protect_register_report_artifact() returns trigger language plpgsql as $$
begin
  if TG_OP='INSERT' then
    if NEW.module_id='REGISTER_REPORT' and NEW.scan_status is distinct from 'GENERATED' then
      raise exception 'Register report artifacts must be generated by the application';
    end if;
  elsif (OLD.module_id='REGISTER_REPORT' or NEW.module_id='REGISTER_REPORT')
    and (to_jsonb(NEW)-array['scan_status','scan_detail']) is distinct from
        (to_jsonb(OLD)-array['scan_status','scan_detail']) then
    raise exception 'Register report artifact identity is immutable';
  end if;
  return NEW;
end $$;
create trigger register_report_artifact_identity before insert or update on replacement_register.artifacts
  for each row execute function replacement_register.protect_register_report_artifact();
insert into replacement_register.schema_migrations(version) values ('036_register_reports');
